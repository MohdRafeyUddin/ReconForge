"""provider_keys.py
=================
Manages API keys for passive recon providers (SecurityTrails, Censys, Shodan,
VirusTotal, GitHub, Chaos) and generates Subfinder provider-config.yaml in WSL.
"""

import json
import logging
import os
import platform
import subprocess
import tempfile
from typing import Any, Dict, Optional

logger = logging.getLogger("reconforge.core.provider_keys")

SUPPORTED_PROVIDERS = [
    "securitytrails",
    "censys",
    "shodan",
    "virustotal",
    "github",
    "chaos",
]


def _get_provider_keys_path() -> str:
    base_dir = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    config_dir = os.path.join(base_dir, "config")
    os.makedirs(config_dir, exist_ok=True)
    return os.path.join(config_dir, "provider_keys.json")


def load_provider_keys() -> Dict[str, Any]:
    """Loads provider keys from local JSON file. Returns empty dict if absent."""
    path = _get_provider_keys_path()
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
            return data if isinstance(data, dict) else {}
    except Exception as exc:
        logger.warning(f"Could not load provider_keys.json: {exc}")
        return {}


def mask_key(val: Any) -> str:
    """Masks a secret API key for safe UI and API presentation."""
    if not val:
        return ""
    if isinstance(val, list):
        return ", ".join(mask_key(item) for item in val if item)
    s = str(val).strip()
    if len(s) <= 4:
        return "***"
    return s[:2] + "*" * (len(s) - 4) + s[-2:]


def get_masked_keys_status() -> Dict[str, Dict[str, Any]]:
    """Returns safe masked status of all supported provider keys (never reveals secrets)."""
    raw_keys = load_provider_keys()
    status = {}
    for prov in SUPPORTED_PROVIDERS:
        val = raw_keys.get(prov)
        is_configured = bool(val)
        status[prov] = {
            "configured": is_configured,
            "masked": mask_key(val) if is_configured else "",
        }
    return status


def save_provider_keys(keys_data: Dict[str, Any]) -> bool:
    """Saves provider keys to local config and triggers WSL Subfinder config sync."""
    path = _get_provider_keys_path()
    try:
        cleaned = {}
        for prov in SUPPORTED_PROVIDERS:
            val = keys_data.get(prov)
            if val:
                cleaned[prov] = val
        with open(path, "w", encoding="utf-8") as f:
            json.dump(cleaned, f, indent=2)

        sync_subfinder_config_to_wsl()
        return True
    except Exception as exc:
        logger.error(f"Failed to save provider keys: {exc}")
        return False


def sync_subfinder_config_to_wsl() -> bool:
    """
    Generates ~/.config/subfinder/provider-config.yaml in WSL based on provider_keys.json.
    Never logs secret values.
    """
    keys = load_provider_keys()
    if not keys:
        return True

    # Construct YAML lines
    yaml_lines = ["# Subfinder provider configuration generated by ReconForge", ""]
    for prov in SUPPORTED_PROVIDERS:
        val = keys.get(prov)
        if not val:
            yaml_lines.append(f"{prov}: []")
            continue
        yaml_lines.append(f"{prov}:")
        if isinstance(val, list):
            for item in val:
                if item:
                    yaml_lines.append(f"  - {item}")
        elif isinstance(val, dict):
            # e.g. Censys id:secret
            c_id = val.get("id") or val.get("api_id") or ""
            c_sec = val.get("secret") or val.get("api_secret") or ""
            if c_id and c_sec:
                yaml_lines.append(f"  - {c_id}:{c_sec}")
        else:
            yaml_lines.append(f"  - {str(val).strip()}")
        yaml_lines.append("")

    yaml_content = "\n".join(yaml_lines) + "\n"

    # Write to temp file then copy to WSL ~/.config/subfinder/provider-config.yaml
    if platform.system().lower() == "windows":
        try:
            with tempfile.NamedTemporaryFile("w", delete=False, suffix=".yaml", encoding="utf-8") as tf:
                tf.write(yaml_content)
                temp_path = tf.name

            drive, rest = os.path.splitdrive(os.path.abspath(temp_path))
            drive_letter = drive.rstrip(":").lower()
            wsl_temp = f"/mnt/{drive_letter}{rest.replace('\\', '/')}"

            # Command: mkdir -p ~/.config/subfinder && cp <wsl_temp> ~/.config/subfinder/provider-config.yaml
            subprocess.run(
                ["wsl", "-e", "mkdir", "-p", "/root/.config/subfinder"],
                capture_output=True,
                check=False,
                timeout=5,
            )
            subprocess.run(
                ["wsl", "-e", "bash", "-c", "mkdir -p ~/.config/subfinder"],
                capture_output=True,
                check=False,
                timeout=5,
            )
            subprocess.run(
                ["wsl", "-e", "bash", "-c", f"cp '{wsl_temp}' ~/.config/subfinder/provider-config.yaml"],
                capture_output=True,
                check=False,
                timeout=5,
            )
            try:
                os.unlink(temp_path)
            except OSError:
                pass
            logger.info("Synchronized Subfinder API keys to WSL ~/.config/subfinder/provider-config.yaml")
            return True
        except Exception as exc:
            logger.warning(f"Could not synchronize Subfinder API keys to WSL: {exc}")
            return False
    else:
        # Native Linux
        try:
            subfinder_dir = os.path.expanduser("~/.config/subfinder")
            os.makedirs(subfinder_dir, exist_ok=True)
            with open(os.path.join(subfinder_dir, "provider-config.yaml"), "w", encoding="utf-8") as f:
                f.write(yaml_content)
            return True
        except Exception as exc:
            logger.warning(f"Could not write Subfinder config: {exc}")
            return False
